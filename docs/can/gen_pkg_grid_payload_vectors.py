# Golden vectors for the Package ToF grid PAYLOAD: 64 zones of uint16 distance plus uint8 status,
# one flat 192-byte block.
#
# WHAT IS AND IS NOT SETTLED HERE. The field WIDTHS come from the requirements document ("uint16
# distances, uint8 status") and are not negotiable. The BYTE ORDER does not: the requirement says
# nothing about it, so the ordering these vectors pin -- distance most significant byte first, then
# status, zones ascending -- is a CANDIDATE CONVENTION. It is pinned so that changing it is loud.
# Nothing here settles the per-frame header, the number of frames, or how metadata is associated:
# this file knows only about the payload.
#
# WHY A SECOND IMPLEMENTATION. A generator that mirrors the C++ shift arithmetic proves only that
# the same mistake was made twice. This one uses struct.pack('>H', ...) and byte concatenation --
# no shifts, no masks -- so agreement on 192 bytes means the field order and widths are right in a
# way one implementation cannot assert about itself.
#
# It lives in docs/can/ because scripts/check_language_boundary.sh allows Python nowhere else, and
# the header it writes says in its own first lines that it is not a frozen contract.

import io
import os
import struct

ZONES = 64
BYTES_PER_ZONE = 3
PAYLOAD_BYTES = ZONES * BYTES_PER_ZONE


def pack(distances, statuses):
    """Distance big-endian, then status, zones ascending. Candidate convention."""
    out = b''
    for d, s in zip(distances, statuses):
        out += struct.pack('>H', d) + bytes([s])
    assert len(out) == PAYLOAD_BYTES, len(out)
    return list(out)


def case_zeros():
    return [0] * ZONES, [0] * ZONES


def case_max():
    # 0xFFFF is carried verbatim: the codec must not read it as "invalid".
    return [0xFFFF] * ZONES, [0xFF] * ZONES


def case_boundary():
    # Every value a 16-bit distance can be argued about, including both bytes' extremes and the
    # 12-bit boundaries that only matter to the candidate 12-bit layout.
    d_cycle = [0x0000, 0x0001, 0x00FF, 0x0100, 0x0FFE, 0x0FFF, 0x1000, 0xFFFE, 0xFFFF]
    # 0 = data not updated, 5 = valid, 6 and 9 = low confidence, 255 = no target detected (UM3038).
    s_cycle = [0, 5, 6, 9, 254, 255]
    return ([d_cycle[z % len(d_cycle)] for z in range(ZONES)],
            [s_cycle[z % len(s_cycle)] for z in range(ZONES)])


def case_walk():
    # Co-prime strides so no zone shares a value with its neighbour: a one-zone shift cannot pass.
    return ([(z * 1021 + 7) & 0xFFFF for z in range(ZONES)],
            [(z * 37 + 5) & 0xFF for z in range(ZONES)])


def case_sentinel_alternate():
    # Half the field of view reporting no target, which is what a real grid looks like with a
    # package on one side. Note the pairing is deliberately NOT self-consistent in the upstream
    # sense -- the codec has no opinion about which status accompanies 0xFFFF.
    return ([0xFFFF if z % 2 else (z * 17) & 0xFFFF for z in range(ZONES)],
            [255 if z % 2 else 5 for z in range(ZONES)])


def case_contradictory():
    # 0xFFFF with a "valid" status, and 0 mm with "no target". Upstream rules may forbid both; the
    # codec must carry them unchanged, because a codec that fixed them would be making the
    # judgement FW-2 says firmware does not make.
    return ([0xFFFF if z < 32 else 0 for z in range(ZONES)],
            [5 if z < 32 else 255 for z in range(ZONES)])


CASES = [
    ('zeros', case_zeros),
    ('max', case_max),
    ('boundary', case_boundary),
    ('walk', case_walk),
    ('sentinel_alternate', case_sentinel_alternate),
    ('contradictory', case_contradictory),
]


def emit(out):
    out.write('/*\n')
    out.write(' * AUTO-GENERATED by gen_pkg_grid_payload_vectors.py -- DO NOT EDIT.\n')
    out.write(' *\n')
    out.write(' * Golden vectors for the Package ToF grid payload: 64 zones of uint16 distance\n')
    out.write(' * plus uint8 status, 192 bytes.\n')
    out.write(' *\n')
    out.write(' * The field WIDTHS are required (uint16 / uint8). The BYTE ORDER pinned here is a\n')
    out.write(' * CANDIDATE CONVENTION -- the requirement does not specify one. Nothing here\n')
    out.write(' * settles the per-frame header, the frame count, or metadata association, and no\n')
    out.write(' * SHA is pinned on this header in either repository. Production source may not\n')
    out.write(' * include it.\n')
    out.write(' */\n\n')
    out.write('#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n')
    out.write('namespace pkg_grid_vectors {\n\n')
    out.write('inline constexpr size_t kZones{%d};\n' % ZONES)
    out.write('inline constexpr size_t kBytesPerZone{%d};\n' % BYTES_PER_ZONE)
    out.write('inline constexpr size_t kPayloadBytes{%d};\n\n' % PAYLOAD_BYTES)
    out.write('struct vector {\n')
    out.write('    const char *name;\n')
    out.write('    uint16_t distance_mm[kZones];\n')
    out.write('    uint8_t status[kZones];\n')
    out.write('    uint8_t payload[kPayloadBytes];\n')
    out.write('};\n\n')
    out.write('inline constexpr vector kVectors[]{\n')
    for name, fn in CASES:
        distances, statuses = fn()
        payload = pack(distances, statuses)
        out.write('    {\n        "%s",\n' % name)
        out.write('        {' + ', '.join('0x%04X' % d for d in distances) + '},\n')
        out.write('        {' + ', '.join('0x%02X' % s for s in statuses) + '},\n')
        out.write('        {' + ', '.join('0x%02X' % b for b in payload) + '},\n')
        out.write('    },\n')
    out.write('};\n\n')
    out.write('inline constexpr size_t kVectorCount{sizeof kVectors / sizeof kVectors[0]};\n\n')
    out.write('}\n')


DEFAULT_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           'tof_pkg_grid_payload_vectors.h')


def main(argv):
    check = '--check' in argv
    args = [a for a in argv if not a.startswith('--')]
    path = args[0] if args else DEFAULT_OUT

    buf = io.StringIO()
    emit(buf)
    if check:
        with open(path, encoding='utf-8') as f:
            if f.read() != buf.getvalue():
                print('STALE: %s does not match the generator' % path)
                return 1
        print('%s is up to date' % path)
        return 0

    with open(path, 'w', encoding='utf-8') as f:
        f.write(buf.getvalue())
    print('%d payload bytes, %d vectors' % (PAYLOAD_BYTES, len(CASES)))
    return 0


if __name__ == '__main__':
    import sys
    sys.exit(main(sys.argv[1:]))
